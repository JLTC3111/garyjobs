import {build} from 'esbuild';
import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

const root = new URL('../', import.meta.url);
const output = new URL('supabase/functions/jobs-profile-avatar/index.ts', root);
const {outputFiles} = await build({
  absWorkingDir: fileURLToPath(root),
  entryPoints: ['supabase/functions/_shared/jobs-profile-avatar.ts'],
  bundle: true,
  platform: 'neutral',
  format: 'esm',
  target: 'es2022',
  write: false,
  banner: {js: '// @ts-nocheck\n// Generated by node scripts/bundle-profile-avatar.mjs.'},
});
const standalone = outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== standalone) {
    throw new Error('Jobs avatar bundle is stale. Run node scripts/bundle-profile-avatar.mjs.');
  }
} else {
  await writeFile(output, standalone);
}
